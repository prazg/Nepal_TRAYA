let currentLang = 'en';

export function getLanguageMeta(code = currentLang) {
  const normalized = String(code || 'en').trim().toLowerCase();
  return SUPPORTED_LANGUAGES.find(l => l.code === normalized) || SUPPORTED_LANGUAGES[0];
}

export function isDevanagariLang(code = currentLang) {
  const normalized = String(code || 'en').trim().toLowerCase();
  return normalized !== 'en' && VALID_LANG_CODES.has(normalized);
}

export function initLang() {
  try {
    const saved = String(localStorage.getItem(STORAGE_KEY) || '').trim().toLowerCase();
    if (VALID_LANG_CODES.has(saved)) {
      currentLang = saved;
    }
  } catch {
    // ignore storage errors
  }
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = currentLang;
  }
  return currentLang;
}

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  const code = String(lang || '').trim().toLowerCase();
  currentLang = VALID_LANG_CODES.has(code) ? code : 'en';
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = currentLang;
  }
  try {
    localStorage.setItem(STORAGE_KEY, currentLang);
  } catch {
    // ignore storage errors
  }
  return currentLang;
}

export function t(key, params, langOverride = null) {
  const code = langOverride && VALID_LANG_CODES.has(String(langOverride).toLowerCase())
    ? String(langOverride).toLowerCase()
    : currentLang;
  const table = I18N[code] || I18N.en;
  let str = Object.prototype.hasOwnProperty.call(table, key)
    ? table[key]
    : (I18N.en[key] || key);
  if (params) {
    Object.keys(params).forEach(k => {
      str = str.replaceAll(`{${k}}`, String(params[k]));
    });
  }
  return str;
}

