export function tProvince(prov, districtsMeta) {
  if (!prov) return '—';
  if (currentLang === 'en') return prov;
  if (districtsMeta && Array.isArray(districtsMeta.provinces)) {
    const match = districtsMeta.provinces.find(p => p.name === prov);
    if (match && match.name_ne) return match.name_ne;
  }
  return PROVINCE_NE[prov] || prov;
}

export function tDistrict(name, districtsMeta) {
  if (!name) return '—';
  if (currentLang === 'en') return name;
  if (districtsMeta && Array.isArray(districtsMeta.districts)) {
    const match = districtsMeta.districts.find(d => d.name === name);
    if (match && match.name_ne) return match.name_ne;
  }
  return name;
}

export function applyStaticTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.setAttribute('placeholder', t(key));
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.setAttribute('title', t(key));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (key) el.setAttribute('aria-label', t(key));
  });
  // Hide the companion static Nepali notice in all 5 Devanagari Nepal languages
  // so the banner never displays two duplicate Devanagari disclaimers side by side.
  root.querySelectorAll('.safety-ne').forEach(el => {
    el.hidden = currentLang !== 'en';
  });
  // Show linguistic-review draft notice when viewing a draft regional language
  const meta = getLanguageMeta();
  root.querySelectorAll('[data-lang-draft-notice]').forEach(el => {
    el.hidden = meta.reviewStatus !== 'draft_pending_native_review';
  });
}
